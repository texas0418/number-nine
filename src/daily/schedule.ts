//
// AUTHORING CONSTRAINTS (all enforced — test-cipher.ts, and the crossover
// fairness sweep in test-site.ts's sibling checks):
//   · A-Z, space and apostrophe only. No digits, no punctuation.
//   · Every line carries at least TWO DISTINCT words of >=5 letters. The B4
//     crossover card asks "what did I say tonight" and re-deals with a
//     different true word each time; a line with one long word pins the
//     answer.
//   · No word longer than 11 letters. Two reasons: the crossover offers
//     decoys within two letters of the answer (crossover.ts DECOY_POOL,
//     longest 11), so a 13-letter word cannot fill four card slots; and the
//     cryptogram cell grid (DailySignalScreen boxSizes) only just fits a
//     12-letter word at the largest Dynamic Type size, with no headroom.
//   · Roughly 22-46 characters. Shorter is a thin cryptogram; longer
//     overflows the card.
//
// The serial is FREE and read by players who have not bought the story, so it
// deepens the prequel without giving away a gate's answer. Where it does
// carry a figure the book later wants (the cellar door, the licence), that is
// deliberate cross-pollination — AGENTS.md asks for clues scattered into the
// daily signal.

